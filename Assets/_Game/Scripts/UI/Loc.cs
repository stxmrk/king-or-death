        // Match time as m:ss, or h:mm:ss past an hour.
        public static string Clock(float seconds)
        {
            int t = Mathf.FloorToInt(Mathf.Max(0, seconds));
            return t >= 3600 ? $"{t / 3600}:{t / 60 % 60:00}:{t % 60:00}" : $"{t / 60}:{t % 60:00}";
        }

        public static string F(string key, params object[] args) => string.Format(T(key), args);

        // Display name for a place or unit title; the English title stays the id in saves and code.
        public static string Name(string id) => id == null ? null : T("name." + id, id);

        public static bool Has(string key) => table.ContainsKey(key);

        public static string T(string key) => T(key, key);

        public static string T(string key, string fallback) =>
            table.TryGetValue(key, out var v) ? v[GameSettings.Language == "ru" ? 1 : 0] : fallback;

        public static void SetLanguage(string language)
        {
            if (language == GameSettings.Language)
                return;
            GameSettings.Language = language;
            Changed?.Invoke();
        }

        // UXML stores keys as text; the key is kept in userData so a language switch can re-translate.
        public static void Apply(VisualElement root)
        {
            root.Query<TextElement>()
                .ForEach(te =>
                {
                    if (!(te.userData is string key))
                    {
                        if (!Has(te.text))
                            return;
                        key = te.text;
                        te.userData = key;
                    }
                    te.text = T(key);
                });
        }
